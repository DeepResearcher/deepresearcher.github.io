const body = document.body;
const page = body.dataset.servicePage;
const languageButtons = document.querySelectorAll("[data-lang]");
const menuToggle = document.querySelector(".menu-toggle");
const primaryNav = document.querySelector(".primary-nav");
const metaDescription = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const selected = language === "en" ? "en" : "de";
  const dictionary = {
    ...commonTranslations[selected],
    ...(pageTranslations[page]?.[selected] || {})
  };

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.documentElement.lang = selected;
  if (dictionary["meta.title"]) document.title = dictionary["meta.title"];
  if (metaDescription && dictionary["meta.description"]) metaDescription.content = dictionary["meta.description"];

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === selected;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try {
    localStorage.setItem("narli-language", selected);
  } catch (error) {}
}

languageButtons.forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.lang)));

menuToggle?.addEventListener("click", () => {
  const open = primaryNav?.classList.toggle("is-open") ?? false;
  menuToggle.setAttribute("aria-expanded", String(open));
  body.classList.toggle("menu-open", open);
});

primaryNav?.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  primaryNav.classList.remove("is-open");
  menuToggle?.setAttribute("aria-expanded", "false");
  body.classList.remove("menu-open");
}));

const year = document.getElementById("year");
if (year) year.textContent = new Date().getFullYear();

let initialLanguage = "de";
try {
  initialLanguage = localStorage.getItem("narli-language") || "de";
} catch (error) {}
setLanguage(initialLanguage);

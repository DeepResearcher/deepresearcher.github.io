const languageButtons = document.querySelectorAll("[data-lang]");
const translatableElements = document.querySelectorAll("[data-i18n]");
const menuToggle = document.querySelector(".menu-toggle");
const primaryNav = document.querySelector(".primary-nav");
const header = document.querySelector(".site-header");
const metaDescription = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const selectedLanguage = translations[language] ? language : "de";
  const dictionary = translations[selectedLanguage];

  translatableElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.documentElement.lang = selectedLanguage;
  document.title = selectedLanguage === "de"
    ? "NARLI DIGITAL — Digitale Outputs für europäische Projekte"
    : "NARLI DIGITAL — Digital Outputs for European Projects";

  if (metaDescription) {
    metaDescription.content = selectedLanguage === "de"
      ? "NARLI DIGITAL entwickelt Websites, Apps, Serious Games, KI-Lösungen und digitale Outputs für europäische Projekte."
      : "NARLI DIGITAL develops websites, apps, serious games, AI solutions and digital outputs for European projects.";
  }

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === selectedLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  try {
    localStorage.setItem("narli-language", selectedLanguage);
  } catch (error) {
    // The site remains usable when browser storage is unavailable.
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

menuToggle?.addEventListener("click", () => {
  const isOpen = primaryNav?.classList.toggle("is-open") ?? false;
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  document.body.classList.toggle("menu-open", isOpen);
});

primaryNav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    primaryNav.classList.remove("is-open");
    menuToggle?.setAttribute("aria-expanded", "false");
    document.body.classList.remove("menu-open");
  });
});

window.addEventListener("scroll", () => {
  header?.classList.toggle("is-scrolled", window.scrollY > 12);
}, { passive: true });

const observer = "IntersectionObserver" in window
  ? new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12 })
  : null;

document.querySelectorAll(".reveal").forEach((element) => {
  if (observer) observer.observe(element);
  else element.classList.add("is-visible");
});

const yearElement = document.getElementById("year");
if (yearElement) yearElement.textContent = new Date().getFullYear();

let initialLanguage = "de";
try {
  initialLanguage = localStorage.getItem("narli-language") || "de";
} catch (error) {
  initialLanguage = "de";
}
setLanguage(initialLanguage);